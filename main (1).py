@app.post("/api/readings", status_code=201)
def post_readings(body: Any = Body(...)):
    items = body if isinstance(body, list) else [body]
    rows = []
    for it in items:
        r = normalize(it)
        if r is None:
            return err(400, 'each reading needs numeric "devices" and "people" (or "smoothed")')
        rows.append(r)
    return save_readings(rows)


# History
@app.get("/api/readings")
def get_readings(zone: Optional[str] = None, since: float = 0, limit: int = 100):
    limit = min(max(limit, 1), 1000)
    with db_lock:
        if zone:
            cur = db.execute(
                "SELECT * FROM readings WHERE zone = ? AND ts >= ? ORDER BY ts DESC LIMIT ?",
                (zone, since, limit),
            )
        else:
            cur = db.execute("SELECT * FROM readings WHERE ts >= ? ORDER BY ts DESC LIMIT ?", (since, limit))
        return [dict(r) for r in cur.fetchall()]


# Latest reading for each zone, busiest first
@app.get("/api/zones")
def get_zones():
    with db_lock:
        rows = db.execute(
            """
            SELECT r.* FROM readings r
            JOIN (SELECT zone, MAX(ts) AS m FROM readings GROUP BY zone) x
              ON r.zone = x.zone AND r.ts = x.m
            GROUP BY r.zone
            ORDER BY r.people DESC
            """
        ).fetchall()
        now = now_ms()
        return [
            {**dict(r), "age_ms": now - r["ts"], "stale": now - r["ts"] > STALE_MS, "mode": current_mode(r["zone"])["mode"]}
            for r in rows
        ]


@app.get("/api/readings/latest")
def get_latest(zone: str = "default"):
    with db_lock:
        row = db.execute("SELECT * FROM readings WHERE zone = ? ORDER BY ts DESC LIMIT 1", (zone,)).fetchone()
    if row is None:
        return err(404, "no readings for zone")
    age = now_ms() - row["ts"]
    return {**dict(row), "age_ms": age, "stale": age > STALE_MS}


# Simple trend forecast: linear regression over a recent window
@app.get("/api/forecast")
def get_forecast(zone: str = "default", window: float = 15, horizons: str = "5,10,15"):
    window = min(max(window, 2), 240)
    hs = []
    for h in horizons.split(","):
        v = num(h)
        if v is not None and 0 < v <= 120:
            hs.append(v)
    since = now_ms() - int(window * 60_000)
    with db_lock:
        rows = db.execute(
            "SELECT ts, people FROM readings WHERE zone = ? AND ts >= ? ORDER BY ts", (zone, since)
        ).fetchall()
    if len(rows) < 5:
        return err(422, "not enough data in window", points=len(rows))

    last_ts = rows[-1]["ts"]
    xs = [(r["ts"] - last_ts) / 60_000 for r in rows]  # minutes, <= 0
    ys = [r["people"] for r in rows]
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    slope = 0.0 if sxx == 0 else sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sxx  # people/min
    intercept = my - slope * mx

    return {
        "zone": zone,
        "points": n,
        "window_min": window,
        "current": ys[-1],
        "slope_per_min": round(slope, 3),
        "trend": "rising" if slope > 0.5 else "falling" if slope < -0.5 else "steady",
        "forecast": [{"in_min": h, "people": max(0.0, round(intercept + slope * h, 1))} for h in hs],
    }


