# ---------- Database ----------
SCHEMA = """
CREATE TABLE IF NOT EXISTS readings (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    zone         TEXT    NOT NULL DEFAULT 'default',
    ts           INTEGER NOT NULL,          -- epoch ms (server time unless supplied)
    devices      REAL    NOT NULL,
    real_devices REAL,
    rand_devices REAL,
    smoothed     REAL,
    people       REAL    NOT NULL,
    level        TEXT    NOT NULL DEFAULT 'UNKNOWN'
);
CREATE INDEX IF NOT EXISTS idx_readings_zone_ts ON readings (zone, ts);

CREATE TABLE IF NOT EXISTS mode_events (
    id    INTEGER PRIMARY KEY AUTOINCREMENT,
    zone  TEXT    NOT NULL DEFAULT '*',     -- '*' = all zones
    mode  TEXT    NOT NULL,
    ts    INTEGER NOT NULL,
    note  TEXT
);
CREATE INDEX IF NOT EXISTS idx_mode_zone_ts ON mode_events (zone, ts);
"""

db = sqlite3.connect(DB_PATH, check_same_thread=False)
db.row_factory = sqlite3.Row
db_lock = threading.RLock()  # MQTT thread + FastAPI threadpool share one connection
with db_lock:
    db.execute("PRAGMA journal_mode = WAL")
    db.executescript(SCHEMA)
    db.commit()

INSERT_READING = """
INSERT INTO readings (zone, ts, devices, real_devices, rand_devices, smoothed, people, level)
VALUES (:zone, :ts, :devices, :real_devices, :rand_devices, :smoothed, :people, :level)
"""

# ---------- Live stream (SSE) ----------
subscribers: set = set()
main_loop: Optional[asyncio.AbstractEventLoop] = None
zone_online: dict[str, bool] = {}


def broadcast(event: str, data: dict) -> None:
    """Thread-safe: callable from the MQTT thread or the request threadpool."""
    if main_loop is None:
        return
    msg = f"event: {event}\ndata: {json.dumps(data)}\n\n"

    def push():
        for q in list(subscribers):
            try:
                q.put_nowait(msg)
            except asyncio.QueueFull:
                pass

    main_loop.call_soon_threadsafe(push)


# ---------- Helpers ----------
def now_ms() -> int:
    return int(time.time() * 1000)


def num(v) -> Optional[float]:
    if v is None or v == "" or isinstance(v, bool):
        return None
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return f if math.isfinite(f) else None


def normalize(p: Any, zone_hint: Optional[str] = None) -> Optional[dict]:
    """Validate and normalize a counts payload without supplying missing values."""
    required = {"devices", "real", "rand", "smoothed", "people", "level"}
    if not isinstance(p, dict) or set(p) != required:
        return None
    devices = num(p.get("devices"))
    real_devices = num(p.get("real"))
    rand_devices = num(p.get("rand"))
    smoothed = num(p.get("smoothed"))
    people = num(p.get("people"))
    level = p.get("level")
    if (
        any(value is None or value < 0 for value in (devices, real_devices, rand_devices, smoothed, people))
        or not isinstance(level, str)
        or not level
    ):
        return None
    return {
        "zone": zone_hint,
        "ts": now_ms(),
        "devices": devices,
        "real_devices": real_devices,
        "rand_devices": rand_devices,
        "smoothed": smoothed,
        "people": people,
        "level": level.upper(),
    }


def save_readings(rows: list) -> list:
    saved = []
    with db_lock, db:  # one transaction
        for r in rows:
            cur = db.execute(INSERT_READING, r)
            saved.append({"id": cur.lastrowid, **r})
    for row in saved:
        broadcast("reading", row)
    return saved


def current_mode(zone: Optional[str] = None) -> dict:
    q = "SELECT zone, mode, ts, note FROM mode_events WHERE zone = ? ORDER BY ts DESC, id DESC LIMIT 1"
    with db_lock:
        row = None
        if zone and zone != "*":
            row = db.execute(q, (zone,)).fetchone()
        if row is None:
            row = db.execute(q, ("*",)).fetchone()
    return dict(row) if row else {"zone": "*", "mode": "normal", "ts": None, "note": None}


def err(status: int, message: str, **extra) -> JSONResponse:
    return JSONResponse({"error": message, **extra}, status_code=status)


# ---------- MQTT ingest ----------
mqtt_client = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, client_id="crowd-backend")
mqtt_client.reconnect_delay_set(min_delay=1, max_delay=5)


def on_connect(client, userdata, flags, reason_code, properties):
    print(f"MQTT connected to {MQTT_HOST}:{MQTT_PORT} ({reason_code})")
    client.subscribe(f"{MQTT_TOPIC}/+/online")
    client.subscribe(f"{MQTT_TOPIC}/+/counts")


def parse_topic(topic: str) -> tuple[Optional[str], Optional[str]]:
    prefix = f"{MQTT_TOPIC}/"
    parts = topic.split("/")
    if not topic.startswith(prefix) or len(parts) != 3 or parts[2] not in {"online", "counts"}:
        return None, None
    zone = parts[1]
    return (zone, parts[2]) if zone else (None, None)


def on_message(client, userdata, msg):
    try:
        zone, kind = parse_topic(msg.topic)
        if zone is None:
            print("MQTT: ignored unsupported topic:", msg.topic)
            return
        payload = msg.payload.decode("utf-8", "strict")
        if kind == "online":
            if payload != "online":
                print("MQTT: ignored invalid online payload for", zone)
                return
            zone_online[zone] = True
            broadcast("online", {"zone": zone, "online": True})
            return
        r = normalize(json.loads(payload), zone)
        if r is None:
            print("MQTT: ignored invalid counts payload for", zone)
            return
        save_readings([r])
    except Exception as e:  # keep the MQTT thread alive on bad input
        print("MQTT: bad message:", e)


mqtt_client.on_connect = on_connect
mqtt_client.on_message = on_message


# ---------- Retention ----------
def prune() -> None:
    cutoff = now_ms() - RETENTION_DAYS * 86_400_000
    with db_lock, db:
        cur = db.execute("DELETE FROM readings WHERE ts < ?", (cutoff,))
    if cur.rowcount:
        print(f"Pruned {cur.rowcount} old readings")


async def prune_loop():
    while True:
        await asyncio.to_thread(prune)
        await asyncio.sleep(3600)


# ---------- Routing (zone graph, route advice, rescue priorities) ----------
routing = Routing(db, db_lock, STALE_MS, current_mode, broadcast, now_ms, seed_demo=SEED_DEMO)


# ---------- App ----------
@asynccontextmanager
async def lifespan(app: FastAPI):
    global main_loop
    main_loop = asyncio.get_running_loop()
    mqtt_client.connect_async(MQTT_HOST, MQTT_PORT, keepalive=60)
    mqtt_client.loop_start()
    tasks = [asyncio.create_task(prune_loop()), asyncio.create_task(routing.loop(ROUTE_INTERVAL))]
    yield
    for t in tasks:
        t.cancel()
    mqtt_client.loop_stop()
    mqtt_client.disconnect()
    with db_lock:
        db.close()


app = FastAPI(title="Crowd density backend", lifespan=lifespan)
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])
app.include_router(routing.api)


