@app.post("/api/mode", status_code=201)
def post_mode(body: dict = Body(...)):
    mode = body.get("mode")
    zone = str(body.get("zone") or "*")[:64]
    note = body.get("note")
    if mode not in MODES:
        return err(400, f"mode must be one of: {', '.join(MODES)}")
    ts = now_ms()
    with db_lock, db:
        db.execute("INSERT INTO mode_events (zone, mode, ts, note) VALUES (?, ?, ?, ?)", (zone, mode, ts, note))
    ev = {"zone": zone, "mode": mode, "ts": ts, "note": note}
    broadcast("mode", ev)
    return ev


# Live updates (Server-Sent Events) for dashboards
@app.get("/api/stream")
async def stream(request: Request):
    q: asyncio.Queue = asyncio.Queue(maxsize=100)
    subscribers.add(q)

    async def gen():
        try:
            yield "retry: 3000\n\n"
            while True:
                if await request.is_disconnected():
                    break
                try:
                    yield await asyncio.wait_for(q.get(), timeout=25)
                except asyncio.TimeoutError:
                    yield ": ping\n\n"
        finally:
            subscribers.discard(q)

    return StreamingResponse(
        gen(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "Connection": "keep-alive"},
    )


